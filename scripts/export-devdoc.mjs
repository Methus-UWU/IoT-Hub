#!/usr/bin/env node
/**
 * Copies the developer documentation set into devdoc/ for hand-off (e.g. upload to a
 * shared drive). The files under docs/ and README.md stay the single source of truth;
 * devdoc/ is output. Re-run after any of them changes instead of editing the copies.
 *
 * Files are numbered to match the documentation checklist. docs/diagrams/ is copied
 * as devdoc/diagrams/ so the relative image links in the copied Markdown still work.
 * Existing files in devdoc/ with other names are left alone.
 *
 * Usage:
 *   node scripts/export-devdoc.mjs
 */

import { copyFileSync, cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'devdoc');

const documents = [
  ['README.md', '01-README.md', '1. README', 'What the project is, how it works, install and run, usage'],
  ['docs/ARCHITECTURE.md', '02-ARCHITECTURE.md', '2. Architecture', 'System diagram, technology choices, folder and module structure'],
  ['docs/API.md', '03-API.md', '3. API Documentation', 'All endpoints, request/response formats, usage examples'],
  ['docs/DATABASE.md', '04-DATABASE.md', '4. Database Schema', 'ER diagram, tables and relationships, indexes'],
  ['docs/CONFIGURATION.md', '05-CONFIGURATION.md', '5. Setup & Configuration', 'Environment variables, dependencies, deployment steps'],
  ['docs/DEPLOYMENT.md', '05-DEPLOYMENT.md', '5. Setup & Configuration', 'Production deployment details, smoke test, rollback'],
  ['docs/CONVENTIONS.md', '06-CONVENTIONS.md', '6. Code Standards', 'Naming, structure, comment rules'],
  ['AGENTS.md', '06-AGENTS.md', '6. Code Standards', 'Core engineering and security rules for this project'],
  ['docs/KNOWN_ISSUES.md', '07-KNOWN_ISSUES.md', '7. Known Issues & Future Plans', 'Known bugs and limitations, planned work'],
];

mkdirSync(out, { recursive: true });
for (const [source, target] of documents) {
  copyFileSync(join(root, source), join(out, target));
}
cpSync(join(root, 'docs/diagrams'), join(out, 'diagrams'), {
  recursive: true,
  filter: (path) => !/\.(mjs|cjs)$/.test(path),
});
cpSync(join(root, 'docs/adr'), join(out, 'adr'), { recursive: true });

const rows = documents.map(([source, target, topic, contents]) => `| ${topic} | \`${target}\` | ${contents} | \`${source}\` |`);
writeFileSync(
  join(out, '00-INDEX.md'),
  `# IoT Hub — Developer Documentation

Generated by \`node scripts/export-devdoc.mjs\` on ${new Date().toISOString().slice(0, 10)}.
These are copies; the sources in the repository are authoritative.

| Topic | File | Contents | Source |
| --- | --- | --- | --- |
${rows.join('\n')}
| 2. Architecture | \`adr/\` | Architecture decision records: the reasons behind each major choice | \`docs/adr/\` |
| 2. / 4. Diagrams | \`diagrams/\` | \`system-overview.png\`, ER diagram as PNG, SVG, PDF, and interactive HTML | \`docs/diagrams/\` |

Paths such as \`docs/SECURITY.md\` inside the documents refer to the repository.
Mermaid diagrams appear as source text in viewers without Mermaid support; the
rendered image is \`diagrams/system-overview.png\`.
`,
);

console.log(`Exported ${documents.length} documents, adr/, and diagrams/ to ${out}`);
