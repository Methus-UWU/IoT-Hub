/**
 * Exports the dashboard widget catalog to the NestJS API.
 *
 * The widget types and their grid sizes are authored once, in
 * `dashboard-builder.models.ts`. The API needs the same facts to validate a saved
 * dashboard and to place the widgets the assistant proposes, so this derives its copy
 * instead of anyone keeping a second one by hand. Titles, icons, and descriptions stay
 * in the frontend: no server decision depends on them.
 *
 * Run it from `frontend/`:
 *
 *   node_modules/@esbuild/win32-x64/esbuild.exe scripts/export-widget-catalog.ts \
 *     --bundle --platform=node --format=cjs --outfile=.tmp/export-widgets.cjs \
 *     && node .tmp/export-widgets.cjs
 */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import {
  BREAKPOINT_CONFIG,
  WIDGET_DEFINITIONS,
} from '../src/app/features/user/workspace/dashboard-builder/dashboard-builder.models';

const target = resolve(
  __dirname,
  '../../backend/src/modules/dashboards/widget-catalog.generated.ts',
);

const widgets = WIDGET_DEFINITIONS.map((definition) => ({
  type: definition.type,
  category: definition.category,
  defaultSize: definition.defaultSize,
  minSize: definition.minSize,
  maxSize: definition.maxSize,
}));
const columns = Object.fromEntries(
  Object.entries(BREAKPOINT_CONFIG).map(([breakpoint, config]) => [breakpoint, config.columns]),
);

writeFileSync(
  target,
  `// Generated by frontend/scripts/export-widget-catalog.ts. Do not edit by hand.\n\n` +
    `export const BREAKPOINT_COLUMNS = ${JSON.stringify(columns, null, 2)} as const;\n\n` +
    `export const WIDGET_CATALOG = ${JSON.stringify(widgets, null, 2)} as const;\n`,
);
console.log(`Wrote ${widgets.length} widget types to ${target}`);
