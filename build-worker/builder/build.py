"""Builder entrypoint: one firmware build, then exit.

Runs inside an ephemeral container started with --network=none, a read-only root,
no capabilities, and a non-root user. The dispatcher writes one JSON request to
stdin and reads one JSON result line from stdout. Everything PlatformIO prints goes
to stderr, which the dispatcher keeps as the build log.

The project source is hostile. It is written only below /workspace (a size-limited
tmpfs), and platformio.ini is generated here from the allowlist in targets.json --
a project's own platformio.ini never reaches PlatformIO, so it cannot add
extra_scripts, change the platform, or ask for packages the image does not hold.

Exit codes: 0 built, 1 compile failed, 2 request rejected.
"""

from __future__ import annotations

import base64
import json
import os
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

TARGETS = json.loads(Path("/opt/iot-hub/targets.json").read_text())
LIBRARY_DIR = "/opt/iot-hub/libraries"
PROJECT_DIR = Path("/workspace/project")
# Installed packages, read-only in the image.
INSTALLED_CORE_DIR = Path(os.environ["PLATFORMIO_CORE_DIR"])
# PlatformIO writes lock and state files beside its package folders, so each
# build gets a core directory on the tmpfs that links back to the installed ones.
BUILD_CORE_DIR = Path("/tmp/platformio-core")
ENV_NAME = "firmware"

MAX_REQUEST_BYTES = 12 * 1024 * 1024
MAX_FILES = 500
ALLOWED_ROOTS = ("src", "include", "lib")
# Same segment rule as project files (backend project-file-path.ts).
SEGMENT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")

# Images an ESP32 (classic) Arduino build is flashed with. Where each one goes is
# decided by the API (build-plan.ts), not reported from here.
ESP32_IMAGES = ("bootloader.bin", "partitions.bin", "boot_app0.bin", "firmware.bin")


class Rejected(Exception):
    """The request is malformed or asks for something this image does not allow."""


def log(message: str) -> None:
    print(message, file=sys.stderr, flush=True)


def finish(code: int, result: dict) -> None:
    sys.stdout.write(json.dumps(result) + "\n")
    sys.stdout.flush()
    sys.exit(code)


def read_request() -> dict:
    raw = sys.stdin.buffer.read(MAX_REQUEST_BYTES + 1)
    if len(raw) > MAX_REQUEST_BYTES:
        raise Rejected("Build request is too large.")
    try:
        request = json.loads(raw)
    except ValueError as error:
        raise Rejected("Build request is not valid JSON.") from error
    if not isinstance(request, dict):
        raise Rejected("Build request must be an object.")
    return request


def resolve_target(request: dict) -> tuple[str, dict, str]:
    target = request.get("target")
    if not isinstance(target, dict):
        raise Rejected("Build target is missing.")
    platform_id = target.get("platform")
    board = target.get("board")
    platform = TARGETS["platforms"].get(platform_id) if isinstance(platform_id, str) else None
    if platform is None or board not in platform["boards"]:
        raise Rejected(f"Board {board!r} on {platform_id!r} is not available in this builder.")
    return platform_id, platform, board


def safe_relative_path(raw: object) -> PurePosixPath:
    if not isinstance(raw, str) or "\\" in raw or "\x00" in raw:
        raise Rejected("Invalid source path.")
    path = PurePosixPath(raw)
    parts = path.parts
    if (
        path.is_absolute()
        or len(parts) < 2
        or len(parts) > 13
        or parts[0] not in ALLOWED_ROOTS
        or any(part in (".", "..") or not SEGMENT.match(part) for part in parts)
    ):
        raise Rejected(f"Source path {raw!r} is not allowed.")
    return path


def write_sources(request: dict) -> int:
    files = request.get("files")
    if not isinstance(files, list) or not files or len(files) > MAX_FILES:
        raise Rejected("The build has no source files.")
    for entry in files:
        if not isinstance(entry, dict) or not isinstance(entry.get("content"), str):
            raise Rejected("Invalid source file.")
        relative = safe_relative_path(entry.get("path"))
        destination = PROJECT_DIR.joinpath(*relative.parts)
        destination.parent.mkdir(parents=True, exist_ok=True)
        # O_EXCL: a repeated path is a malformed request, not an overwrite.
        with open(destination, "x", encoding="utf-8") as handle:
            handle.write(entry["content"])
    return len(files)


def write_config(platform: dict, board: str) -> None:
    (PROJECT_DIR / "platformio.ini").write_text(
        "\n".join(
            [
                "; Generated by the platform builder. A project's own platformio.ini is not used.",
                "[platformio]",
                f"default_envs = {ENV_NAME}",
                "",
                f"[env:{ENV_NAME}]",
                f"platform = {platform['spec']}",
                f"board = {board}",
                "framework = arduino",
                f"lib_extra_dirs = {LIBRARY_DIR}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def prepare_core_dir() -> None:
    BUILD_CORE_DIR.mkdir(parents=True)
    for name in ("packages", "platforms"):
        (BUILD_CORE_DIR / name).symlink_to(INSTALLED_CORE_DIR / name, target_is_directory=True)
    appstate = INSTALLED_CORE_DIR / "appstate.json"
    if appstate.exists():
        (BUILD_CORE_DIR / "appstate.json").write_bytes(appstate.read_bytes())


def run_platformio() -> int:
    prepare_core_dir()
    process = subprocess.run(
        ["pio", "run", "--project-dir", str(PROJECT_DIR), "--environment", ENV_NAME],
        stdin=subprocess.DEVNULL,
        stdout=sys.stderr,
        stderr=sys.stderr,
        env={**os.environ, "PLATFORMIO_CORE_DIR": str(BUILD_CORE_DIR)},
        check=False,
    )
    return process.returncode


def artifact(path: Path, name: str) -> dict:
    return {"name": name, "data": base64.b64encode(path.read_bytes()).decode("ascii")}


def collect_artifacts(platform_id: str) -> list[dict]:
    build_dir = PROJECT_DIR / ".pio" / "build" / ENV_NAME
    if platform_id == "atmelavr":
        return [artifact(build_dir / "firmware.hex", "firmware.hex")]

    boot_app0 = (
        INSTALLED_CORE_DIR / "packages" / "framework-arduinoespressif32" / "tools" / "partitions" / "boot_app0.bin"
    )
    sources = {"boot_app0.bin": boot_app0}
    return [artifact(sources.get(name, build_dir / name), name) for name in ESP32_IMAGES]


def main() -> None:
    try:
        request = read_request()
        platform_id, platform, board = resolve_target(request)
        PROJECT_DIR.mkdir(parents=True)
        count = write_sources(request)
        write_config(platform, board)
    except Rejected as error:
        log(f"error: {error}")
        finish(2, {"ok": False, "reason": "rejected", "message": str(error)})
        return

    log(f"Building {count} source file(s) for {board} ({platform['spec']})")
    if run_platformio() != 0:
        finish(1, {"ok": False, "reason": "compile"})
        return

    try:
        artifacts = collect_artifacts(platform_id)
    except OSError as error:
        log(f"error: build produced no flashable image ({error.strerror})")
        finish(1, {"ok": False, "reason": "artifacts"})
        return
    finish(0, {"ok": True, "artifacts": artifacts})


if __name__ == "__main__":
    main()
